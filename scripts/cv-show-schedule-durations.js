import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { CV_SHOW_PRESENTATION_PROJECT } from '../src/static-pages/data/cvShowPresentationProject.js';
import { CV_SHOW_WEB_AUDIO_RELEASE } from '../src/static-pages/data/cvShowWebAudioRelease.js';
import {
  createCvShowEntryTuple,
  createCvShowMediaBindingRegistry,
} from '../src/static-pages/js/tour-player/presentationProjectAdapter.js';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const audioBase = path.join(rootDir, 'src/static-pages/copy-cv-show-audio');
const outputPath = path.join(rootDir, 'src/static-pages/data/cvShowScheduleDurations.js');

const manifestRelativePath = CV_SHOW_WEB_AUDIO_RELEASE.manifest.path;
const manifest = JSON.parse(await readFile(path.join(audioBase, manifestRelativePath), 'utf8'));
const mediaRegistry = createCvShowMediaBindingRegistry(CV_SHOW_PRESENTATION_PROJECT);
const noopAdapter = {
  playAudioClip: () => undefined,
  runInteraction: () => undefined,
  runAttention: () => undefined,
  waitForState: () => undefined,
};

const durations = {};
for (const clip of manifest.clips) {
  const sequenceBytes = await readFile(
    path.join(audioBase, path.dirname(manifestRelativePath), clip.alignedSequenceFile),
  );
  const sequence = JSON.parse(sequenceBytes.toString('utf8'));
  const tuple = createCvShowEntryTuple(CV_SHOW_PRESENTATION_PROJECT, clip.id, sequence, {
    adapter: noopAdapter,
    mediaAncestry: mediaRegistry,
  });
  const durationMs = Number(tuple.schedule.totalDurationMs);
  if (!Number.isSafeInteger(durationMs) || durationMs <= 0) {
    throw new Error(`CV Show schedule duration is invalid for ${clip.id}: ${durationMs}`);
  }
  durations[clip.id] = durationMs;
}

const payload = `/**
 * Generated by scripts/cv-show-schedule-durations.js. Regenerate whenever the
 * CV Show audio release or presentation master changes.
 */
export const CV_SHOW_SCHEDULE_DURATIONS = Object.freeze({
  releaseId: '${CV_SHOW_WEB_AUDIO_RELEASE.releaseId}',
  durations: Object.freeze(${JSON.stringify(durations, null, 2)}),
});
`;
await writeFile(outputPath, payload, 'utf8');
process.stdout.write(`cv-show-schedule-durations: wrote ${Object.keys(durations).length} entries\n`);
